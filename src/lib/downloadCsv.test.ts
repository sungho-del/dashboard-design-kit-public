import { toCsv } from "./downloadCsv";

describe("toCsv", () => {
  it("행은 CRLF, 칸은 쉼표로 잇는다", () => {
    expect(
      toCsv([
        ["No", "이름"],
        [1, "박수진"],
      ]),
    ).toBe("No,이름\r\n1,박수진");
  });

  it("쉼표·따옴표·줄바꿈이 든 칸은 따옴표로 감싼다", () => {
    expect(toCsv([["렌트 1, 구매 2", '그 "상품"', "두\n줄"]])).toBe(
      '"렌트 1, 구매 2","그 ""상품""","두\n줄"',
    );
  });

  it("수식으로 읽힐 글자 칸은 무력화하고, 숫자 칸은 그대로 둔다", () => {
    expect(toCsv([["=SUM(A1)", "+82", "@x", -3]])).toBe(
      "'=SUM(A1),'+82,'@x,-3",
    );
  });
});
