/* -------------------------------------------------------------------------
 * S26 약관 관리 — **도메인 층** (BabyCube 본사 운영 어드민)
 *
 * 짝이 되는 뼈대: `TermsAdminPage.tsx` (레이아웃·상호작용, 도메인 무관)
 * 원본 템플릿: `src/pages/ProductFormPage.data.ts` (폼형)
 *
 * ## 이 화면이 무엇인가
 * 가입·결제 화면에 노출되는 약관 문서를 **좌측에서 고르고 우측에서 본문을 쓴다.**
 * 문서 종류는 고정이고(추가·삭제가 없다) 바뀌는 것은 **본문과 최종 수정일**뿐이다.
 *
 * ## ⚠️ 폼형이라 데이터로 다 빠지지 않는다
 * 필드가 **본문 Textarea 하나**뿐이라 뼈대가 단순하지만,
 * **어떤 필드가 있고 무엇이 필수인지는 뼈대의 JSX 에 남아 있다.**
 * 이 파일이 드는 것은 "값의 나열"(문서 목록)과 포맷터다.
 *
 * ## 뼈대가 이 파일에 기대하는 계약
 * - `TERMS[]` 의 `id` 는 좌측 목록의 선택 키다 (원본도 `docKey` 하나로 고른다)
 * - **`body === ""` 가 "미작성"의 유일한 정의다.** 별도 상태 필드를 두지 않는다 —
 *   두 곳에 두면 본문을 저장했는데 배지가 남는 어긋남이 생긴다.
 *   저장 버튼 라벨(`등록`/`수정 저장`)도 같은 값에서 갈린다
 * - `updatedAt` 은 `""`(한 번도 저장한 적 없음) 이거나 `YYYY-MM-DD`
 * - `TERMS` 가 **빈 배열이어도 화면이 성립해야 한다** — 뼈대가 우측에 빈 상태를 그린다
 * ---------------------------------------------------------------------- */

export interface TermsDoc {
  /** 문서 키 — 좌측 목록과 Select 가 공유한다 */
  id: string;
  /** 사용자에게 보이는 문서 명칭 */
  name: string;
  /** 동의가 필수인 문서인가. 필수인데 미작성이면 가입 화면에 빈 약관이 뜬다 */
  required: boolean;
  /** 본문. **빈 문자열이면 미작성** */
  body: string;
  /** 최종 수정일 `YYYY-MM-DD`. 한 번도 저장한 적 없으면 `""` */
  updatedAt: string;
}

