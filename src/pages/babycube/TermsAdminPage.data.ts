/**
 * 편집 카드 헤더의 우측 문구. 한 번도 저장한 적 없으면 `미작성` 이다.
 * ⚠️ 원본 문구 그대로다 — "저장된 본문이 없습니다" 같은 말로 늘리지 말 것.
 */
export const updatedText = (doc: Pick<TermsDoc, "updatedAt">) =>
  doc.updatedAt === "" ? "미작성" : `최종 수정 ${doc.updatedAt}`;

/** `Date` → `YYYY-MM-DD`. 저장 시 최종 수정일을 찍는다 */
export const ymd = (date: Date = new Date()) => {
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${date.getFullYear()}-${month}-${day}`;
};
