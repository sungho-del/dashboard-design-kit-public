/**
 * 편집 카드 헤더의 우측 문구. 한 번도 저장한 적 없으면 `미작성` 이다(원본 3582).
 * ⚠️ 원본 문구 그대로다 — "저장된 본문이 없습니다" 같은 말로 늘리지 말 것.
 */
export const updatedText = (doc: Pick<TermsDoc, "updatedAt">) =>
  doc.updatedAt === ""
    ? "미작성"
    : `최종 수정 ${doc.updatedAt.replace(/-/g, ".")}`;

/** `YYYY-MM-DD` → 그날 0시(로컬) */
export const dateOf = (ymd: string) => {
  const [y, m, d] = ymd.split("-").map(Number);
  return new Date(y, m - 1, d);
};

