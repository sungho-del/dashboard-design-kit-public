export interface TermsDoc {
  /** 문서 키 — 좌측 목록의 선택 키 */
  id: string;
  /** 사용자에게 보이는 문서 명칭 */
  name: string;
  /** 필수 약관인가. 법정 또는 마켓플레이스 운영상 필요한 약관 */
  required: boolean;
  /** 본문. **빈 문자열이면 미작성** */
  body: string;
  /** 최종 수정일 `YYYY-MM-DD`. 한 번도 저장한 적 없으면 `""` */
  updatedAt: string;
  /** 개정 예정본(예약). 없으면 전환·[예약 취소] 가 나오지 않는다 — 판정 Q15 */
  scheduled?: TermsSchedule;
}

/** 개정 예정본 — 시행일에 현행본과 자동 교체된다(서버 일) */
export interface TermsSchedule {
  /** 개정 예정본 본문 */
  body: string;
  /** 시행일 `YYYY-MM-DD` */
  effectiveAt: string;
}

