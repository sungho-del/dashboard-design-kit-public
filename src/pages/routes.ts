/* =========================================================================
 * 템플릿 4종의 경로 — **단일 원천**
 *
 * ## 왜 상수로 모으나
 *
 * 화면끼리 이동하는 자리(주문 목록 → 주문 상세, 상품 등록 → 뒤로)가 경로 문자열을
 * 직접 들고 있으면, 경로를 바꿀 때 **App.tsx 만 고치고 화면 안쪽을 놓친다.**
 * 그러면 메뉴는 멀쩡한데 화면 안의 버튼만 죽는다 — 타입도 린트도 잡지 못한다.
 * 둘 다 그냥 문자열이기 때문이다.
 *
 * ## 실제로 그렇게 깨져 있었다
 *
 * 예전에는 `onNavSelect("order-detail")` 처럼 **상대 경로**를 넘겼다. 브라우저가
 * 현재 경로를 기준으로 이어 붙이는 데 기대는 방식이라 `/_template/orders` 에서는
 * 우연히 `/_template/order-detail` 로 맞아떨어졌지만,
 *
 *   - `onNavSelect("order-list")` 는 `/_template/order-list` 가 되어 **없는 경로**였고
 *     (주문 상세의 뒤로가기가 화면 목록으로 떨어졌다)
 *   - 경로 체계를 바꾸는 순간 나머지도 전부 어긋났다
 *
 * 그래서 **절대 경로 상수**로 바꿨다. 현재 위치에 기대지 않는다.
 *
 * ## 바꿀 때
 *
 * 여기만 고치면 `App.tsx`(라우팅) · `ScreenIndexPage.data.ts`(화면 목록) ·
 * 화면 안의 이동 버튼이 함께 따라온다. `npm run reset:project` 도 이 파일을
 * 갈아끼우는 것으로 경로 체계를 통째로 바꾼다.
 * ====================================================================== */

